  @{ x=160; y=32; name='large_greenhouse';                     art=$greenhouse }
  @{ x=176; y=32; name='large_ranch';                          art=$ranch }
  @{ x=192; y=32; name='ore_crusher';                          art=$crusher }
)

foreach ($ic in $icons) {
  $art = $ic.art
  if ($art.Count -ne 16) { throw "$($ic.name): 行数 $($art.Count) != 16" }
  for ($y = 0; $y -lt 16; $y++) {
    $row = $art[$y]
    if ($row.Length -ne 16) { throw "$($ic.name) 第 $y 行长度 $($row.Length) != 16" }
    for ($x = 0; $x -lt 16; $x++) {
      $ch = $row[$x]
      if ($ch -eq '.') { continue }
      if (-not $palette.ContainsKey($ch)) { throw "$($ic.name): 未知字符 '$ch'" }
      $bmp.SetPixel($ic.x + $x, $ic.y + $y, $palette[$ch])
    }
  }
  Write-Host ("  绘制 {0,-38} @ ({1},{2})" -f $ic.name, $ic.x, $ic.y)
}

