$icons = @(
  @{ x=80;  y=32; name='hunter_process_reactor';               art=$hunter }
  @{ x=96;  y=32; name='kroll_reduction_vessel';               art=$kroll }
  @{ x=112; y=32; name='cultivation_vessel';                   art=$culture }
  @{ x=128; y=32; name='irradiated_mutagensis_chamber';        art=$mutagen }
